/**
 * Writes the FheCat, FheCatArena and launchpad ABIs for the web app (web/src/config/abi.ts).
 *
 *   npm run export:abi   (after `npx hardhat compile`)
 */
import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const abi = (name: string) =>
  JSON.parse(readFileSync(join(__dirname, '..', 'artifacts', 'contracts', `${name}.sol`, `${name}.json`), 'utf8')).abi;
const fheCat = abi('FheCat');
const arena = abi('FheCatArena');
const launchpad = JSON.parse(readFileSync(join(__dirname, '..', 'artifacts', 'contracts', 'launchpad', 'FheLaunchpad.sol', 'FheLaunchpad.json'), 'utf8')).abi;
const launchToken = JSON.parse(readFileSync(join(__dirname, '..', 'artifacts', 'contracts', 'launchpad', 'FheLaunchToken.sol', 'FheLaunchToken.json'), 'utf8')).abi;
const rewards = JSON.parse(readFileSync(join(__dirname, '..', 'artifacts', 'contracts', 'launchpad', 'FheCatRewards.sol', 'FheCatRewards.json'), 'utf8')).abi;
const out = join(__dirname, '..', '..', 'web', 'src', 'config', 'abi.ts');
writeFileSync(
  out,
  `// AUTO-GENERATED by contracts/scripts/export-abi.ts. Do not edit by hand.\n` +
    `export const fheCatAbi = ${JSON.stringify(fheCat, null, 2)} as const;\n\n` +
    `export const fheCatArenaAbi = ${JSON.stringify(arena, null, 2)} as const;\n\n` +
    `export const fheLaunchpadAbi = ${JSON.stringify(launchpad, null, 2)} as const;\n\n` +
    `export const fheLaunchTokenAbi = ${JSON.stringify(launchToken, null, 2)} as const;\n\n` +
    `export const fheCatRewardsAbi = ${JSON.stringify(rewards, null, 2)} as const;\n`,
);
console.log(`wrote ${out} (FheCat ${fheCat.length}, FheCatArena ${arena.length}, launchpad ${launchpad.length + launchToken.length + rewards.length} entries)`);
