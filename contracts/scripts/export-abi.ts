/**
 * Writes the FheCat ABI for the web app (web/src/config/abi.ts).
 *
 *   npm run export:abi   (after `npx hardhat compile`)
 */
import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const artifact = JSON.parse(
  readFileSync(join(__dirname, '..', 'artifacts', 'contracts', 'FheCat.sol', 'FheCat.json'), 'utf8'),
);
const out = join(__dirname, '..', '..', 'web', 'src', 'config', 'abi.ts');
writeFileSync(
  out,
  `// AUTO-GENERATED by contracts/scripts/export-abi.ts. Do not edit by hand.\n` +
    `export const fheCatAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log(`wrote ${out} (${artifact.abi.length} entries)`);
