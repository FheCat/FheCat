/**
 * Writes the FheCat and FheCatArena ABIs for the web app (web/src/config/abi.ts).
 *
 *   npm run export:abi   (after `npx hardhat compile`)
 */
import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const abi = (name: string) =>
  JSON.parse(readFileSync(join(__dirname, '..', 'artifacts', 'contracts', `${name}.sol`, `${name}.json`), 'utf8')).abi;
const fheCat = abi('FheCat');
const arena = abi('FheCatArena');
const out = join(__dirname, '..', '..', 'web', 'src', 'config', 'abi.ts');
writeFileSync(
  out,
  `// AUTO-GENERATED by contracts/scripts/export-abi.ts. Do not edit by hand.\n` +
    `export const fheCatAbi = ${JSON.stringify(fheCat, null, 2)} as const;\n\n` +
    `export const fheCatArenaAbi = ${JSON.stringify(arena, null, 2)} as const;\n`,
);
console.log(`wrote ${out} (FheCat ${fheCat.length}, FheCatArena ${arena.length} entries)`);
