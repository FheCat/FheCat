/**
 * Compiles the art in /art into contracts/art/FheCatArt.sol, the data library
 * the on-chain renderer draws from. Run after changing any sprite or trait:
 *
 *   npm run art:sol
 */
import { writeFileSync } from 'fs';
import { join } from 'path';
import { ART } from '../../art';
import * as R from '../../art/src/render';
import { FUR_ROLES, type Layer } from '../../art/src/types';

const hex = (bytes: number[]) => 'hex"' + bytes.map((b) => b.toString(16).padStart(2, '0')).join('') + '"';
const u16 = (n: number) => {
  if (n > 0xffff) throw new Error('offset overflow');
  return [n >> 8, n & 0xff];
};
const u8 = (n: number) => {
  if (n < 0 || n > 0xff) throw new Error(`byte overflow ${n}`);
  return n;
};
const str = (s: string) => {
  if (/["\\\n]/.test(s) || /[^\x20-\x7e]/.test(s)) throw new Error(`unsafe string literal: ${s}`);
  return `"${s}"`;
};

// Layers ---------------------------------------------------------------------
const encodeLayer = (layer: Layer) =>
  layer.flatMap((g) => [u8(g.color), u8(g.rects.length), ...g.rects.flatMap((r) => r.map(u8))]);

const layerBytes: number[] = [];
const layerOffsets: number[] = [];
for (const layer of ART.layers) {
  layerOffsets.push(...u16(layerBytes.length));
  layerBytes.push(...encodeLayer(layer));
}
layerOffsets.push(...u16(layerBytes.length));

// Traits ---------------------------------------------------------------------
const optionCounts = ART.traits.map((t) => u8(t.names.length));
const weights = ART.traits.flatMap((t) => t.weights.map(u8));
const optionLayers = ART.traits.flatMap((t) => t.layers.map((l) => u8(l < 0 ? 255 : l)));
const names = [...ART.traits.map((t) => t.label), ...ART.traits.flatMap((t) => t.names)];
const nameBytes: number[] = [];
const nameOffsets: number[] = [];
for (const n of names) {
  nameOffsets.push(...u16(nameBytes.length));
  nameBytes.push(...Buffer.from(n, 'ascii'));
}
nameOffsets.push(...u16(nameBytes.length));

const colors = ART.colors.flatMap((h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16)));

// Output bounds, so the renderer can allocate its buffer once -----------------
const PATH_OPEN = '<path fill="#000000" d="'.length;
const PATH_CLOSE = '"/>'.length;
const rectLen = ([x, y, w, h]: number[]) => `M${x} ${y}h${w}v${h}h-${w}z`.length;
const layerLen = (id: number) =>
  id < 0 ? 0 : ART.layers[id].reduce((s, g) => s + PATH_OPEN + PATH_CLOSE + g.rects.reduce((a, r) => a + rectLen(r), 0), 0);
const BG_RECT = '<rect width="32" height="32" fill="#000000"/>'.length;
const maxCatSvg =
  R.SVG_OPEN.length +
  BG_RECT +
  layerLen(ART.bodyLayer) +
  layerLen(ART.headLayer) +
  ART.traits.reduce((s, t) => s + Math.max(...t.layers.map(layerLen)), 0) +
  R.SVG_CLOSE.length;
const maxEncryptedSvg =
  R.SVG_OPEN.length + BG_RECT + layerLen(ART.motifLayer) + 2 * (PATH_OPEN + PATH_CLOSE) + 40 * rectLen([25, 28, 1, 1]) + R.SVG_CLOSE.length;

const out = `// SPDX-License-Identifier: MIT
// AUTO-GENERATED by contracts/scripts/gen-art-sol.ts from /art. Do not edit by hand.
pragma solidity ^0.8.28;

/// @notice FheCat pixel-art data: colours, sprite layers and trait tables.
/// @dev Layer = groups back to back; group = [colour, rectCount, (x, y, w, h) * rectCount].
///      Colour bytes below ROLE_COUNT index the cat's fur palette; the rest are COLORS[c - ROLE_COUNT].
library FheCatArt {
    uint256 internal constant ROLE_COUNT = ${FUR_ROLES.length};
    uint256 internal constant TRAIT_COUNT = ${ART.traits.length};
    uint256 internal constant BODY_LAYER = ${ART.bodyLayer};
    uint256 internal constant HEAD_LAYER = ${ART.headLayer};
    uint256 internal constant MOTIF_LAYER = ${ART.motifLayer};
    uint256 internal constant NO_LAYER = 255;
    uint256 internal constant MAX_CAT_SVG_BYTES = ${maxCatSvg};
    uint256 internal constant MAX_ENCRYPTED_SVG_BYTES = ${maxEncryptedSvg};

    string internal constant COLLECTION_NAME = ${str(R.COLLECTION_NAME)};
    string internal constant EXTERNAL_LINK = ${str(R.EXTERNAL_LINK)};
    string internal constant COLLECTION_DESCRIPTION =
        ${str(R.COLLECTION_DESCRIPTION)};
    string internal constant ENCRYPTED_DESCRIPTION =
        ${str(R.ENCRYPTED_DESCRIPTION)};
    string internal constant REVEALED_DESCRIPTION =
        ${str(R.REVEALED_DESCRIPTION)};
    string internal constant SVG_OPEN =
        ${"'" + R.SVG_OPEN + "'"};
    string internal constant SVG_CLOSE = ${str(R.SVG_CLOSE)};
    string internal constant ENCRYPTED_FILL = ${str(R.ENCRYPTED_FILL.slice(1))};
    string internal constant BARCODE_OFF = ${str(R.BARCODE_OFF.slice(1))};
    string internal constant BARCODE_ON = ${str(R.BARCODE_ON.slice(1))};

    /// @dev RGB, 3 bytes per colour.
    bytes internal constant COLORS = ${hex(colors)};

    bytes internal constant LAYERS = ${hex(layerBytes)};

    /// @dev uint16 start offset of each layer in LAYERS, plus the end offset.
    bytes internal constant LAYER_OFFSETS = ${hex(layerOffsets)};

    /// @dev Options per trait, in DNA byte order: ${ART.traits.map((t) => t.label).join(', ')}.
    bytes internal constant OPTION_COUNTS = ${hex(optionCounts)};

    /// @dev Rarity weight of every option (each trait sums to 256).
    bytes internal constant WEIGHTS = ${hex(weights)};

    /// @dev Layer drawn by every option, NO_LAYER for none.
    bytes internal constant OPTION_LAYERS = ${hex(optionLayers)};

    /// @dev Trait labels followed by every option name.
    bytes internal constant NAMES = ${hex(nameBytes)};
    bytes internal constant NAME_OFFSETS = ${hex(nameOffsets)};

    /// @dev Fill colour index of each background.
    bytes internal constant BACKGROUND_FILLS = ${hex(ART.backgroundFills.map(u8))};

    /// @dev ${FUR_ROLES.join(', ')} colour indices per fur.
    bytes internal constant FUR_PALETTES = ${hex(ART.furPalettes.flat().map(u8))};
}
`;

const file = join(__dirname, '..', 'contracts', 'art', 'FheCatArt.sol');
writeFileSync(file, out);
console.log(
  `wrote ${file}\n  colours ${ART.colors.length}, layers ${ART.layers.length}, layer bytes ${layerBytes.length}, ` +
    `names ${nameBytes.length}B, max cat svg ${maxCatSvg}B, max encrypted svg ${maxEncryptedSvg}B`,
);
