#!/usr/bin/env python3
"""
Builds landing/js/pixelfont.js: the site's three pixel fonts (Tiny5, Silkscreen,
Press Start 2P) as bitmaps, so the waitlist card draws its text pixel by pixel
and looks the same in every browser (canvas text rendering of 8px fonts differs
between engines, and a font that is late to load falls back to a system font).

Each glyph is sampled at its native 8px grid (one font pixel = one bitmap pixel).
Run from the repo root:  python3 tools/pixelfont.py   (needs fonttools + brotli)
"""
import json
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.pointInsidePen import PointInsidePen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = {
    'tiny5': 'landing/fonts/tiny5-latin.woff2',
    'silkscreen': 'landing/fonts/silkscreen-latin.woff2',
    'ps2p': 'landing/fonts/press-start-2p-latin.woff2',
}
CHARS = [chr(c) for c in range(32, 127)] + ['·', '…']


def glyphs(path):
    font = TTFont(ROOT / path)
    unit = font['head'].unitsPerEm / 8  # one pixel at the native 8px size
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    out = {}
    for ch in CHARS:
        name = cmap.get(ord(ch))
        if not name:
            continue
        g = gs[name]
        adv = round(g.width / unit)
        bp = BoundsPen(gs)
        g.draw(bp)
        if not bp.bounds:  # space
            out[ch] = [adv, 0, 0, 0, []]
            continue
        x0, y0, x1, y1 = (round(v / unit) for v in bp.bounds)
        rows = []
        for py in range(y1 - 1, y0 - 1, -1):  # top row first
            bits = 0
            for px in range(x0, x1):
                pen = PointInsidePen(gs, ((px + 0.5) * unit, (py + 0.5) * unit))
                g.draw(pen)
                if pen.getResult():
                    bits |= 1 << (px - x0)
            rows.append(bits)
        # [advance, left offset, rows above the baseline, width, row bitmasks (bit 0 = leftmost)]
        out[ch] = [adv, x0, y1, x1 - x0, rows]
    return out


data = {key: glyphs(path) for key, path in FONTS.items()}
js = (
    '/* Generated by tools/pixelfont.py from the fonts in fonts/ (SIL Open Font License). Do not edit. */\n'
    '(function () {\n'
    "  'use strict';\n"
    '  // glyph: [advance, left offset, rows above the baseline, width, row bitmasks (bit 0 = leftmost)]\n'
    '  window.FheCat = window.FheCat || {};\n'
    '  window.FheCat.pixelFonts = ' + json.dumps(data, ensure_ascii=True, separators=(',', ':')) + ';\n'
    '})();\n'
)
(ROOT / 'landing/js/pixelfont.js').write_text(js)
print('wrote landing/js/pixelfont.js', len(js), 'bytes;', {k: len(v) for k, v in data.items()})
